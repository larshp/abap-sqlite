import {SQLiteDatabaseClient} from "@abaplint/database-sqlite";
import {readdir, readFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.join(here, "fixtures");

// must match zcl_sqlite_files=>c_default_block_size
const blockSize = 4096;
const fixturePrefix = "fixtures/";

function sqlString(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function splitBlocks(data) {
  if (data.length === 0) {
    return [Buffer.alloc(0)];
  }

  const blocks = [];
  for (let offset = 0; offset < data.length; offset += blockSize) {
    blocks.push(data.subarray(offset, Math.min(offset + blockSize, data.length)));
  }
  return blocks;
}

async function loadFixture(client, mandt, filename, bytes) {
  const name = `${fixturePrefix}${filename}`;
  const blocks = splitBlocks(bytes);
  const statements = [
    `DELETE FROM zsqlite_files WHERE mandt = ${sqlString(mandt)} AND filename = ${sqlString(name)}`,
  ];

  for (const [blockno, block] of blocks.entries()) {
    statements.push(
      `INSERT INTO zsqlite_files (mandt, filename, blockno, data) VALUES (` +
      `${sqlString(mandt)}, ${sqlString(name)}, ${blockno}, ` +
      `${sqlString(block.toString("hex").toUpperCase())})`,
    );
  }
  await client.execute(statements);

  const {rows} = await client.select({
    select: `SELECT data FROM zsqlite_files ` +
      `WHERE mandt = ${sqlString(mandt)} AND filename = ${sqlString(name)} ` +
      `ORDER BY blockno`,
  });
  const loaded = Buffer.concat(rows.map(row => Buffer.from(row.data, "hex")));
  if (!loaded.equals(bytes)) {
    throw new Error(`${name}: loaded ${loaded.length} bytes, expected ${bytes.length}`);
  }
}

async function loadFixtures(client, abap) {
  const mandt = abap.builtin.sy.get().mandt.get();
  const files = (await readdir(fixturesDir))
    .filter(name => name.endsWith(".db"))
    .sort();

  if (files.length === 0) {
    throw new Error(`no fixtures found in ${fixturesDir}`);
  }

  for (const filename of files) {
    const bytes = await readFile(path.join(fixturesDir, filename));
    await loadFixture(client, mandt, filename, bytes);
  }
}

/**
 * Called by the generated output/_init.mjs before the ABAP Unit tests run.
 *
 * `schemas` and `insert` are generated by the transpiler from the DDIC
 * definitions in src/. Fixtures are committed under test/fixtures and are
 * loaded into ZSQLITE_FILES as files, split into 4096 byte blocks.
 *
 * @param {object} abap the transpiled ABAP runtime instance
 * @param {{sqlite: string[], hdb: string, pg: string[], snowflake: string[]}} schemas
 * @param {string[]} insert
 */
export async function setup(abap, schemas, insert) {
  const client = new SQLiteDatabaseClient({
    trace: process.env.SQLITE_TRACE === "1",
  });

  abap.context.databaseConnections["DEFAULT"] = client;
  await client.connect();

  await client.execute(schemas.sqlite);
  await client.execute(insert);
  await loadFixtures(client, abap);
}
